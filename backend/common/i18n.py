def detect_language(text: str | None) -> str:
    """Return 'hi' for Devanagari, 'hinglish' for Roman-script Hindi, else 'en'."""
    if not text:
        return "en"
    if _DEVANAGARI.search(text):
        return "hi"
    words = re.findall(r"[a-zA-Z]+", text.lower())
    if not words:
        return "en"
    hits = sum(1 for w in words if w in _HINGLISH_WORDS)
    return "hinglish" if hits >= 2 or (hits == 1 and len(words) <= 3) else "en"


