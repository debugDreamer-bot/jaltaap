"""Air quality (India National AQI estimate) and UV index. Pure functions driven by risk.yaml.

Delhi's outdoor workers face two hazards in October to January that heat bands do not cover:
polluted air and, all year, strong sun. The AQI here is an estimate from modelled PM2.5 and PM10
24-hour averages using the CPCB sub-index breakpoints; the official NAQI uses monitoring stations
and at least three pollutants, so every surface labels it "estimate".
"""
from __future__ import annotations

import math

from risk.config_loader import air_config

AQI_ORDER = ["GOOD", "SATISFACTORY", "MODERATE", "POOR", "VERY_POOR", "SEVERE"]
UV_ORDER = ["LOW", "MODERATE", "HIGH", "VERY_HIGH", "EXTREME"]

# Fixed advice keys per AQI category (copy lives in common/i18n.py, never generated by the LLM).
AQI_ADVICE = {
    "GOOD": [],
    "SATISFACTORY": [],
    "MODERATE": ["air_moderate"],
    "POOR": ["air_mask", "air_breaks"],
    "VERY_POOR": ["air_mask", "air_limit_heavy", "air_sensitive_indoors"],
    "SEVERE": ["air_mask", "air_limit_heavy", "air_sensitive_indoors"],
}
UV_ADVICE = {"LOW": [], "MODERATE": [], "HIGH": ["uv_cover"], "VERY_HIGH": ["uv_cover", "uv_shade_noon"],
             "EXTREME": ["uv_cover", "uv_shade_noon"]}


def sub_index(conc: float, table: list[list[float]]) -> int:
    """Linear interpolation inside the breakpoint row that holds the (truncated) concentration."""
    c = math.floor(max(0.0, conc))
    for lo, hi, a_lo, a_hi in table:
        if c <= hi:
            c = max(c, lo)
            return round(a_lo + (a_hi - a_lo) * (c - lo) / (hi - lo))
    return int(table[-1][3])   # beyond the scale: cap at 500


def category(aqi: int, cfg: dict | None = None) -> str:
    for row in (cfg or air_config())["categories"]:
        if aqi <= row["max"]:
            return row["name"]
    return "SEVERE"


def india_aqi(pm2_5_24h: float | None, pm10_24h: float | None, cfg: dict | None = None) -> dict | None:
    """{aqi, category, dominant, pm2_5, pm10, advice_keys} or None without data. The AQI is the
    higher sub-index."""
    cfg = cfg or air_config()
    subs = {}
    if pm2_5_24h is not None:
        subs["pm2_5"] = sub_index(pm2_5_24h, cfg["pm2_5"])
    if pm10_24h is not None:
        subs["pm10"] = sub_index(pm10_24h, cfg["pm10"])
    if not subs:
        return None
    dominant = max(subs, key=subs.get)
    aqi = subs[dominant]
    cat = category(aqi, cfg)
    return {"aqi": aqi, "category": cat, "dominant": dominant, "estimate": True,
            "pm2_5": None if pm2_5_24h is None else round(pm2_5_24h, 1),
            "pm10": None if pm10_24h is None else round(pm10_24h, 1), "advice_keys": AQI_ADVICE[cat]}


def uv_category(uv: float | None, cfg: dict | None = None) -> str | None:
    if uv is None:
        return None
    for row in (cfg or air_config())["uv"]:
        if uv <= row["max"]:
            return row["name"]
    return "EXTREME"


def mean_last(values: list[float | None], end_index: int, hours: int = 24) -> float | None:
    """Mean of the `hours` values ending at end_index (inclusive), skipping gaps; None if under 75 % present."""
    window = [v for v in values[max(0, end_index - hours + 1):end_index + 1] if v is not None]
    if len(window) < 0.75 * hours:
        return None
    return sum(window) / len(window)
